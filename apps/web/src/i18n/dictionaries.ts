export type Dictionary = (typeof dictionaries)[Locale];

export function getDictionary(locale: Locale): Dictionary {
  return dictionaries[locale];
}

/** Maps a server/client error code to a localized message, falling back gracefully. */
export function getAuthErrorMessage(
  dictionary: Dictionary,
  code: AuthErrorCode | ClientErrorCode | string,
): string {
  const errors = dictionary.auth.errors as Record<string, string>;
  return errors[code] ?? errors.UNKNOWN_ERROR ?? dictionary.common.genericError;
}
